namespace {
// The client's certcheck config, as client/ovpncli.cpp setup_certcheck_ssl_config builds it, with
// upstream's test client certificate (and its key, so the handshake can progress).
SSLLib::SSLAPI::Config::Ptr certcheck_config()
{
    SSLLib::SSLAPI::Config::Ptr config(new SSLLib::SSLAPI::Config);
    config->set_frame(new Frame(Frame::Context(128, 4096, 4096 - 128, 0, 16, BufAllocFlags::NO_FLAGS)));
    config->set_mode(Mode(Mode::CLIENT));
    config->set_rng(StrongRandomAPI::Ptr(new fuzz::FixedRand()));
    config->load_cert(fuzzkeys::client_crt, "");
    config->load_private_key(fuzzkeys::client_key);
    config->load_ca(fuzzkeys::ca_crt, false);
    config->set_flags(SSLConst::LOG_VERIFY_STATUS);
    return config;
}

// ClientProto::Session::do_acc_certcheck
void do_acc_certcheck(AccHandshaker &hs, const std::string &msg_str)
{
    AccHandshaker::MsgT msg = std::nullopt;
    if (!msg_str.empty())
        msg = msg_str;
    try
    {
        AccHandshaker::MsgT reply;
        do
        {
            reply = hs.process_msg(msg);
            msg = std::nullopt;
        } while (reply);
    }
    catch (const std::exception &)
    {
    }
}
} // namespace

extern "C" int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size)
{
    static InitProcess::Init init;
    static const std::string certcheck_proto = "cck1"; // ClientProto::Session::certcheckProto

    const std::string in(reinterpret_cast<const char *>(data), size);
    AppControlMessageReceiver acc_recv;
    ProtoContext::ProtoConfig::Ptr conf(new ProtoContext::ProtoConfig);
    std::unique_ptr<AccHandshaker> certcheck_hs;
    OptionList::Limits pushed_options_limit("server-pushed options data too large",
                                                  ProfileParseLimits::MAX_PUSH_SIZE,
                                                  ProfileParseLimits::OPT_OVERHEAD,
                                                  ProfileParseLimits::TERM_OVERHEAD,
                                                  0,
                                                  ProfileParseLimits::MAX_DIRECTIVE_SIZE);

    size_t pos = 0;
    while (pos < in.size())
    {
        size_t nl = in.find('\n', pos);
        if (nl == std::string::npos)
            nl = in.size();
        BufferAllocated app_bp(reinterpret_cast<const unsigned char *>(in.data() + pos), nl - pos, BufAllocFlags::NO_FLAGS);
        pos = nl + 1;

        const std::string msg = ProtoContext::read_control_string<std::string>(app_bp);
        if (!Unicode::is_valid_utf8(msg, Unicode::UTF8_NO_CTRL))
            continue;

        try
        {
            if (ClientHalt::match(msg))
            {
                const ClientHalt ch(msg, true);
                (void)ch.psid();
                (void)ch.restart();
                (void)ch.reason();
                (void)ch.render();
            }
            else if (msg.starts_with("INFO,") || msg.starts_with("INFO_PRE,"))
            {
                const std::string info_msg = msg.substr(msg.starts_with("INFO,") ? 5 : 9);
                if (info_msg.starts_with("ACC:"))
                {
                    const OptionList acc_options = OptionList::parse_from_csv_static("custom-control " + info_msg.substr(4), &pushed_options_limit);
                    conf->parse_custom_app_control(acc_options);
                    (void)conf->app_control_config.str();
                }
            }
            else if (msg.starts_with("AUTH_PENDING,"))
            {
                const OptionList opts = OptionList::parse_from_csv_static(msg.substr(13), nullptr);
                const std::string timeout_str = opts.get_optional("timeout", 1, 20);
                if (!timeout_str.empty())
                {
                    try
                    {
                        (void)clamp_to_typerange<unsigned int>(std::stoul(timeout_str));
                    }
                    catch (const std::logic_error &)
                    {
                    }
                }
            }
            else if (msg.starts_with("ACC,"))
            {
                if (!acc_recv.receive_message(msg))
                    continue;
                auto [proto, app_proto_msg] = acc_recv.get_message();
                if (proto == certcheck_proto)
                {
                    if (!certcheck_hs)
                    {
                        // ClientProto::Session::start_acc_certcheck: reset, then an empty first message.
                        certcheck_hs.reset(new AccHandshaker());
                        certcheck_hs->reset(certcheck_config());
                        do_acc_certcheck(*certcheck_hs, std::string());
                    }
                    do_acc_certcheck(*certcheck_hs, app_proto_msg);
                }
                else
                {
                    (void)conf->app_control_config.supports_protocol(proto);
                }
            }
        }
        catch (const std::exception &)
        {
        }
    }
    return 0;
}
