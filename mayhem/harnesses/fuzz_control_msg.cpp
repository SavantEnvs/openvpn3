// Server -> client control-channel text messages: what the client does with each cleartext control
// message once the TLS session delivers it (openvpn/client/cliproto.hpp ClientProto::Session::
// control_recv). A malicious or compromised server controls all of this text.
//
// The dispatch below follows control_recv branch by branch and calls the same upstream code each
// branch calls:
//   - ProtoContext::read_control_string + Unicode::is_valid_utf8(UTF8_NO_CTRL) on every message
//   - "HALT,..." / "RESTART,[P]:..."  -> ClientHalt (openvpn/client/clihalt.hpp), as recv_halt_restart
//   - "ACC,..."                        -> AppControlMessageReceiver::receive_message / get_message
//                                         (openvpn/ssl/customcontrolchannel.hpp), as
//                                         recv_custom_control_message; a complete "cck1" message
//                                         drives AccHandshaker (openvpn/client/acc_certcheck.hpp), as
//                                         do_acc_certcheck
//   - "INFO,ACC:..." / "INFO_PRE,ACC:" -> OptionList::parse_from_csv_static + ProtoConfig::
//                                         parse_custom_app_control, as recv_info
//   - "AUTH_PENDING,..."               -> OptionList::parse_from_csv_static + the timeout option, as
//                                         recv_auth_pending
// PUSH_REPLY / PUSH_UPDATE are fuzz-push-options' surface and are not repeated here.
//
// Input: one control message per line. A message that passes the client's UTF8_NO_CTRL check has
// no control characters, so splitting on '\n' loses nothing the client would accept.
//
// State: one AppControlMessageReceiver, one ProtoConfig (its app_control_config) and one
// AccHandshaker per input, as one client session has; nothing is kept across inputs except the
// certcheck SSL key material, which is read-only.
#include "fuzz_common.hpp"
