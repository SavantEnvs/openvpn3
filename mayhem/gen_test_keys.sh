#!/usr/bin/env bash
# Writes <outdir>/ovpn_test_keys.hpp: upstream's test PKI (test/ssl/) as string constants, so the
# protocol harnesses carry their keys in the binary instead of reading files at run time.
set -euo pipefail
out="$1/ovpn_test_keys.hpp"
ssl="${SRC:-/mayhem}/test/ssl"
mkdir -p "$1"
{
  echo '// GENERATED by mayhem/gen_test_keys.sh from test/ssl/ -- do not edit.'
  echo '#pragma once'
  echo 'namespace fuzzkeys {'
  for pair in ca_crt:ca.crt server_crt:server.crt server_key:server.key client_crt:client.crt \
              client_key:client.key dh_pem:dh.pem tls_auth_key:tls-auth.key \
              tls_crypt_v2_server_key:tls-crypt-v2-server.key tls_crypt_v2_client_key:tls-crypt-v2-client.key; do
    name="${pair%%:*}"; file="$ssl/${pair#*:}"
    printf 'inline const char %s[] = R"OVPNFUZZKEY(' "$name"
    cat "$file"
    printf ')OVPNFUZZKEY";\n'
  done
  echo '} // namespace fuzzkeys'
} > "$out.tmp"
mv "$out.tmp" "$out"
